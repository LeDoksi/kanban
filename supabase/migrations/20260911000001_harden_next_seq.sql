-- Линтер Supabase ругается на функции без явного search_path: вызывающий
-- может подставить свой и перехватить неквалифицированные имена таблиц.
-- Пустой search_path здесь не годится — тело next_seq ссылается на
-- projects/epics/items без схемы, и функция просто перестала бы их
-- находить. Прибиваем путь к public: дыра закрыта, тело не трогаем.
alter function next_seq(text, text) set search_path = 'public';
